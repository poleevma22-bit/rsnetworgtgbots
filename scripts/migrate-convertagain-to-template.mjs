function ensureTemplate() {
  const existing = listPromptTemplates().find((t) => t.name === TEMPLATE_NAME);
  if (existing) {
    const updated = updatePromptTemplate(existing.id, {
      description: "Скрипт продаж для холодных и тёплых iGaming-лидов (cold + retention pitch). Дружелюбный тон, эскалация на @ConvertAgainSales, рейт-лимит 7 дней между пингами.",
      body: BODY,
      defaults: DEFAULTS,
    });
    console.log(`[migrate] updated template ${updated.id} "${updated.name}" (${updated.variables.length} vars: ${updated.variables.join(", ")})`);
    return updated;
  }
  const created = createPromptTemplate({
    name: TEMPLATE_NAME,
    description: "Скрипт продаж для холодных и тёплых iGaming-лидов (cold + retention pitch).",
    body: BODY,
    defaults: DEFAULTS,
  });
  console.log(`[migrate] created template ${created.id} "${created.name}" (${created.variables.length} vars: ${created.variables.join(", ")})`);
  return created;
}

const tpl = ensureTemplate();
const group = listGroups().find((g) => g.name === GROUP_NAME);
